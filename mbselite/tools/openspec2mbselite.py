#!/usr/bin/env python3
"""Generate mbselite pages from OpenSpec spec files — one page per capability.

Reads   openspec/changes/<change>/specs/<cap-path>/spec.md   (archive excluded)
and     openspec/specs/<cap-path>/spec.md                    (synced main specs)
writes  specs/<change>/<cap-path>.md        one page per capability
        specs/<change>/index.md             the change's index (hierarchy + toctree)
        specs/generated-index.md            toctree of all change indexes
(main specs use <change> = "main").

The OpenSpec file stays the validated source of truth. Generated pages are
never edited by hand: every requirement SHALL sentence and every WHEN/THEN
scenario is copied verbatim into a typed block, IDs are derived
deterministically from the headings, and `verifies` links wire each
scenario to its requirement.

Structure comes for free: every capability gets a `component` block that is
`part_of` its parent capability (by path nesting; top-level capabilities
hang off a change-level component) and `satisfies` all of its requirements,
so a nested spec tree renders as a clickable hierarchy with per-page views
without any hand-written model.

Hand-written model content goes into a companion fragment next to the page,
`<page>.model.md` (for the index: `index.model.md`). The generated page
`{include}`s it instead of synthesising the default blocks, so richer
component / interface / constraint blocks live on the same page as the
requirements they `satisfies`. If the fragment's first line is a `# Heading`,
it becomes the page title. A fragment's component is found by its first
`{component}` block, so children can be `part_of` it. The converter warns
when a fragment leaves requirements of its page unsatisfied.

Conventions read from the OpenSpec text:
  - `## Purpose` prose is copied under the page title
  - a line `Source: ...` or `**Source:** ...` inside a requirement body
    becomes `:source:`; otherwise the spec file path is used
  - the marker `ASSUMED` anywhere in a requirement body sets `:kind: assumed`
  - requirements under `## REMOVED` / `## RENAMED` are skipped

Usage:  openspec2mbselite.py [--root DIR] [--out DIR] [--check]
  --root   project root (default: $MBSELITE_ROOT, else two levels above this
           file, i.e. the project that holds mbselite/tools/)
  --out    output directory (default: <root>/specs)
  --check  exit 1 if any generated file would change (CI / pre-commit use)
"""
from __future__ import annotations

import argparse
import os
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path

MARKER = "<!-- generated by openspec2mbselite.py from OpenSpec - do not edit -->"
# Earlier copies wrote the script's project path into the marker; any first line that
# names the converter counts, so their output is still recognised (and cleaned up).
RE_MARKER = re.compile(r"^<!-- generated by \S*openspec2mbselite\.py from OpenSpec")
GEN_INDEX = "generated-index.md"
MODEL_SUFFIX = ".model.md"

RE_SECTION = re.compile(r"^##\s+(ADDED|MODIFIED|REMOVED|RENAMED)\s+Requirements\s*$", re.I)
RE_PURPOSE = re.compile(r"^##\s+Purpose\s*$", re.I)
RE_REQ = re.compile(r"^###\s+Requirement:\s*(.+?)\s*$")
RE_SC = re.compile(r"^####\s+Scenario:\s*(.+?)\s*$")
RE_H2 = re.compile(r"^##\s+")
RE_SOURCE = re.compile(r"^\**\s*Source\s*:?\**\s*:?\s*(.+?)\s*$", re.I)
RE_ID_OPT = re.compile(r"^:id:\s*(\S+)")
RE_SATISFIES_OPT = re.compile(r"^:satisfies:\s*(.+?)\s*$")


@dataclass
class Scenario:
    title: str
    body: list[str] = field(default_factory=list)


@dataclass
class Requirement:
    title: str
    section: str  # ADDED / MODIFIED / "" (main spec)
    body: list[str] = field(default_factory=list)
    scenarios: list[Scenario] = field(default_factory=list)


@dataclass
class Spec:
    purpose: list[str] = field(default_factory=list)
    requirements: list[Requirement] = field(default_factory=list)


@dataclass
class Capability:
    path: str        # e.g. "hardware/sheets/power-supply"
    spec_file: Path
    id_prefix: str = ""   # from the change's .openspec.yaml (x-mbselite_id_prefix)


@dataclass
class Fragment:
    """A hand-written `<page>.model.md`, if present."""
    path: Path
    title: str | None          # from a leading "# Heading"
    component_id: str | None   # id of its first {component} block
    satisfies: set[str]        # every id named in any :satisfies: option

    @classmethod
    def load(cls, path: Path) -> "Fragment | None":
        if not path.is_file():
            return None
        lines = path.read_text(encoding="utf-8").splitlines()
        title = lines[0][2:].strip() if lines and lines[0].startswith("# ") else None
        comp_id, satisfies, in_component = None, set(), False
        for line in lines:
            if line.startswith("```{component}"):
                in_component = True
            elif line.startswith("```"):
                in_component = False
            m = RE_ID_OPT.match(line)
            if m and in_component and comp_id is None:
                comp_id = m.group(1)
            m = RE_SATISFIES_OPT.match(line)
            if m:
                satisfies.update(s.strip() for s in m.group(1).split(","))
        return cls(path, title, comp_id, satisfies)

    def include(self) -> str:
        inc = [f"```{{include}} {self.path.name}"]
        if self.title:
            inc.append(":start-line: 1")
        inc.append("```")
        return "\n".join(inc)


# ---------------------------------------------------------------- parsing

def parse_spec(path: Path) -> Spec:
    spec = Spec()
    section = ""
    in_purpose = False
    cur_req: Requirement | None = None
    cur_sc: Scenario | None = None
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.rstrip()
        if RE_PURPOSE.match(line):
            in_purpose, cur_req, cur_sc = True, None, None
            continue
        m = RE_SECTION.match(line)
        if m:
            section = m.group(1).upper()
            in_purpose, cur_req, cur_sc = False, None, None
            continue
        m = RE_REQ.match(line)
        if m:
            cur_req = Requirement(title=m.group(1), section=section)
            cur_sc = None
            if section not in ("REMOVED", "RENAMED"):
                spec.requirements.append(cur_req)
            continue
        m = RE_SC.match(line)
        if m and cur_req is not None:
            cur_sc = Scenario(title=m.group(1))
            cur_req.scenarios.append(cur_sc)
            continue
        if RE_H2.match(line):  # any other ## heading ends purpose / requirement
            in_purpose, cur_req, cur_sc = False, None, None
            continue
        if in_purpose:
            spec.purpose.append(line)
        elif cur_sc is not None:
            cur_sc.body.append(line)
        elif cur_req is not None:
            cur_req.body.append(line)
    return spec


# ---------------------------------------------------------------- text helpers

def slug(text: str, limit: int = 40) -> str:
    s = re.sub(r"[^A-Za-z0-9]+", "-", text).strip("-").upper()
    s = re.sub(r"-{2,}", "-", s)
    if len(s) > limit:  # cut at a word boundary, never mid-word
        s = s[:limit]
        s = s.rsplit("-", 1)[0] if "-" in s else s
    return s.rstrip("-") or "X"


def strip_md(text: str) -> str:
    # emphasis and code markers only; underscores stay (identifiers such as net names: VBUS_IN)
    text = re.sub(r"\*+|`+", "", text)
    return re.sub(r"\s+", " ", text).strip()


def clip(s: str, limit: int) -> str:
    return s if len(s) <= limit else s[: limit - 1].rstrip() + "…"


def first_sentence(lines: list[str], limit: int = 140) -> str:
    prose = " ".join(l for l in lines if l.strip() and not RE_SOURCE.match(l.strip()))
    prose = strip_md(prose)
    m = re.match(r"(.+?[.!?])(\s|$)", prose)
    return clip(m.group(1) if m else prose, limit)


def scenario_summary(lines: list[str], limit: int = 120) -> str:
    parts = [strip_md(re.sub(r"^\s*[-*]\s+", "", l)) for l in lines if l.strip()]
    return clip(" ".join(parts), limit)


def find_source(lines: list[str]) -> str | None:
    for l in lines:
        m = RE_SOURCE.match(l.strip())
        if m:
            return strip_md(m.group(1))
    return None


def humanize(path_segment: str) -> str:
    return path_segment.replace("-", " ").replace("_", " ").capitalize()


def opt(name: str, value: str) -> str:
    value = re.sub(r"\s+", " ", value).strip()
    if " #" in value or value.startswith("#"):
        value = '"' + value.replace('"', "'") + '"'
    return f":{name}: {value}"


def fence_for(body: list[str]) -> str:
    longest = 3
    for l in body:
        for run in re.findall(r"`+", l):
            longest = max(longest, len(run) + 1)
    return "`" * longest


def trim_blank(lines: list[str]) -> list[str]:
    while lines and not lines[0].strip():
        lines = lines[1:]
    while lines and not lines[-1].strip():
        lines = lines[:-1]
    return lines


def render_block(kind: str, title: str, options: list[str], body: list[str]) -> str:
    body = trim_blank(body)
    f = fence_for(body)
    out = [f"{f}{{{kind}}} {title}"] + options
    if body:
        out += [""] + body
    out.append(f)
    return "\n".join(out)


def unique(base: str, taken: set[str]) -> str:
    cand, n = base, 2
    while cand in taken:
        cand = f"{base}-{n}"
        n += 1
    taken.add(cand)
    return cand


def default_component_id(path: str, prefix: str = "") -> str:
    return "COMP-" + (prefix + "-" if prefix else "") + slug(path, 60)


def change_id_prefix(root: Path, change: str) -> str:
    """Optional `x-mbselite_id_prefix: XX` in openspec/changes/<change>/.openspec.yaml.
    Two changes with same-named capabilities (hardware/board, firmware/board)
    would otherwise generate the same need IDs."""
    meta = root / "openspec" / "changes" / change / ".openspec.yaml"
    if not meta.is_file():
        return ""
    for line in meta.read_text(encoding="utf-8").splitlines():
        k, _, v = line.partition(":")
        if k.strip() == "x-mbselite_id_prefix":
            return slug(v.strip().strip("\"'"), 8)
    return ""


# ---------------------------------------------------------------- rendering

def render_requirements(spec: Spec, cap_slug: str, rel_spec: str, taken: set[str]) -> tuple[list[str], list[str]]:
    """Return (markdown lines, requirement ids) for the spec's requirements and scenarios."""
    out: list[str] = []
    req_ids: list[str] = []
    for req in spec.requirements:
        rid = unique(f"REQ-{cap_slug}-{slug(req.title, 60)}", taken)
        req_ids.append(rid)
        opts = [opt("id", rid)]
        if "ASSUMED" in " ".join(req.body).upper():
            opts.append(opt("kind", "assumed"))
        elif req.section:
            opts.append(opt("kind", req.section.lower()))
        opts.append(opt("source", find_source(req.body) or rel_spec))
        opts.append(opt("summary", first_sentence(req.body) or req.title))
        out += [render_block("requirement", req.title, opts, req.body), ""]
        for i, sc in enumerate(req.scenarios, 1):
            sid = unique(f"SC-{rid[4:]}-{i}", taken)
            sopts = [
                opt("id", sid),
                opt("source", rel_spec),
                opt("summary", scenario_summary(sc.body) or sc.title),
                opt("verifies", rid),
            ]
            out += [render_block("scenario", sc.title, sopts, sc.body), ""]
    return out, req_ids


def render_default_component(title: str, comp_id: str, rel_spec: str, summary: str,
                             parent_id: str | None, req_ids: list[str]) -> str:
    opts = [opt("id", comp_id), opt("kind", "capability"), opt("source", rel_spec), opt("summary", summary)]
    if parent_id:
        opts.append(opt("part_of", parent_id))
    if req_ids:
        opts.append(opt("satisfies", ", ".join(req_ids)))
    return render_block("component", title, opts, [])


def render_views(docname: str) -> list[str]:
    return [
        "## Views",
        "",
        "```{needflow} Structure and the requirements it satisfies",
        ":config: lr",
        f':filter: docname == "{docname}" and type in ["component", "interface", "artifact", "constraint", "requirement"]',
        ":link_types: satisfies, applies_to, derived_from, part_of, reads",
        ":show_link_names:",
        "```",
        "",
        "```{needflow} Requirements and the scenarios that verify them",
        ":config: lr",
        f':filter: docname == "{docname}" and type in ["requirement", "scenario"]',
        ":link_types: verifies",
        "```",
        "",
        "```{needtable} Requirements",
        f':filter: type == "requirement" and docname == "{docname}"',
        ':columns: id, title, kind, source, satisfies_back as "Satisfied by", verifies_back as "Scenarios"',
        ":style: table",
        "```",
        "",
    ]


def render_capability(cap: Capability, docname: str, rel_spec: str, fragment: Fragment | None,
                      comp_id: str, parent_id: str | None, taken: set[str], notes: list[str]) -> str:
    spec = parse_spec(cap.spec_file)
    cap_slug = slug(cap.path.split("/")[-1], 24)
    if cap.id_prefix:                       # .openspec.yaml `x-mbselite_id_prefix`: keeps IDs unique across changes
        cap_slug = f"{cap.id_prefix}-{cap_slug}"
    title = (fragment.title if fragment and fragment.title else humanize(cap.path.split("/")[-1]))
    req_md, req_ids = render_requirements(spec, cap_slug, rel_spec, taken)

    out: list[str] = [MARKER, "", f"# {title}", ""]
    purpose = trim_blank(spec.purpose)
    if purpose:
        out += purpose + [""]
    out += [
        f"Requirements are generated from `{rel_spec}` — edit that file, not this",
        "page. Boxes link to their blocks; click a diagram to zoom.",
        "",
    ]
    if fragment:
        out += [fragment.include(), ""]
        missing = [r for r in req_ids if r not in fragment.satisfies]
        if missing:
            notes.append(f"{fragment.path.name}: {len(missing)} requirement(s) not in any :satisfies: — " + ", ".join(missing))
    else:
        summary = first_sentence(spec.purpose) or f"{len(req_ids)} requirement(s)"
        out += ["## Model", "", render_default_component(title, comp_id, rel_spec, summary, parent_id, req_ids), ""]
    out += render_views(docname)
    out += ["## Requirements", ""] + req_md
    return "\n".join(out).rstrip() + "\n"


def render_change_index(change: str, title_default: str, pages: list[str], fragment: Fragment | None,
                        root_component: str | None) -> str:
    title = fragment.title if fragment and fragment.title else title_default
    out = [MARKER, "", f"# {title}", ""]
    if fragment:
        out += [fragment.include(), ""]
    if root_component:
        out += [root_component, ""]
    if not fragment:
        out += [
            "```{needflow} Hierarchy — click a box to open its page",
            ":config: default",
            f':filter: type == "component" and ("{change}/" in docname or docname == "{change}/index")',
            ":link_types: part_of",
            "```",
            "",
            "```{needtable} Capabilities and their requirements",
            f':filter: type == "component" and "{change}/" in docname',
            ":columns: id, title, source, satisfies",
            ":style: table",
            "```",
            "",
        ]
    out += ["```{toctree}", ":maxdepth: 1", ""] + pages + ["```", ""]
    return "\n".join(out)


def render_root_index(change_indexes: list[str]) -> str:
    out = [MARKER, "", "# Generated specification pages", "",
           "One index per OpenSpec change (and one for the synced main specs); each",
           "capability has its own page with its model, requirements, scenarios,",
           "diagrams and tables.", "",
           "```{toctree}", ":maxdepth: 2", ""] + change_indexes + ["```", ""]
    return "\n".join(out)


# ---------------------------------------------------------------- collection

def collect(root: Path) -> dict[str, tuple[str, list[Capability]]]:
    """Return {change: (title, [Capability])}."""
    def caps_under(d: Path) -> list[Capability]:
        return [Capability(s.parent.relative_to(d).as_posix(), s) for s in sorted(d.rglob("spec.md"))] if d.is_dir() else []

    docs: dict[str, tuple[str, list[Capability]]] = {}
    changes = root / "openspec" / "changes"
    if changes.is_dir():
        for ch in sorted(p for p in changes.iterdir() if p.is_dir() and p.name != "archive"):
            if caps := caps_under(ch / "specs"):
                docs[ch.name] = (ch.name, caps)
    if caps := caps_under(root / "openspec" / "specs"):
        docs["main"] = ("Main specs", caps)
    return docs


def parent_path(path: str, known: set[str]) -> str | None:
    parts = path.split("/")
    for i in range(len(parts) - 1, 0, -1):
        cand = "/".join(parts[:i])
        if cand in known:
            return cand
    return None


def is_generated(path: Path) -> bool:
    try:
        return bool(RE_MARKER.match(path.read_text(encoding="utf-8")))
    except (OSError, UnicodeDecodeError):
        return False


# ---------------------------------------------------------------- main

def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--root", type=Path, default=Path(os.environ.get("MBSELITE_ROOT") or Path(__file__).resolve().parents[2]))
    ap.add_argument("--out", type=Path, default=None)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    root = a.root.resolve()
    out_dir = (a.out or root / "specs").resolve()
    out_dir.mkdir(parents=True, exist_ok=True)

    wanted: dict[Path, str] = {}
    change_indexes: list[str] = []
    notes: list[str] = []
    owner: dict[str, str] = {}   # id -> change that generated it; a second change with it is a clash
    clashes: list[str] = []
    n_req = 0
    for change, (title, caps) in collect(root).items():
        taken: set[str] = set()
        known = {c.path for c in caps}
        fragments = {c.path: Fragment.load(out_dir / change / (c.path + MODEL_SUFFIX)) for c in caps}
        prefix = change_id_prefix(root, change)
        for c in caps:
            c.id_prefix = prefix
        comp_ids = {p: (f.component_id if f and f.component_id else default_component_id(p, prefix)) for p, f in fragments.items()}
        index_fragment = Fragment.load(out_dir / change / ("index" + MODEL_SUFFIX))
        # What top-level capabilities are part_of: the index fragment's own component if it
        # has one; otherwise a synthesised change-level component, but only when some
        # capability relies on default blocks (a fully hand-modelled change needs none).
        root_block = None
        if index_fragment and index_fragment.component_id:
            root_id = index_fragment.component_id
        elif any(f is None for f in fragments.values()):
            root_id = "COMP-CHANGE-" + slug(change, 54)   # change-level root; distinct from a capability named like the change
            root_block = render_default_component(title, root_id, f"openspec/changes/{change}",
                                                  f"OpenSpec change {change}", None, [])
        else:
            root_id = None

        pages: list[str] = []
        for cap in caps:
            page = out_dir / change / f"{cap.path}.md"
            docname = f"{change}/{cap.path}"
            rel_spec = cap.spec_file.relative_to(root).as_posix()
            parent = parent_path(cap.path, known)
            parent_id = comp_ids[parent] if parent else root_id
            wanted[page] = render_capability(cap, docname, rel_spec, fragments[cap.path],
                                             comp_ids[cap.path], parent_id, taken, notes)
            pages.append(cap.path)
            n_req += len(parse_spec(cap.spec_file).requirements)
        # A change modifying a capability of another change (or of the main specs) gets the
        # same IDs; sphinx-needs would only say "already exists", so name the fix here.
        for i in sorted(taken | set(comp_ids.values())):
            if owner.setdefault(i, change) != change:
                clashes.append(f"{i} (changes {owner[i]} and {change})")
        idx = out_dir / change / "index.md"
        wanted[idx] = render_change_index(change, title, pages, index_fragment, root_block)
        change_indexes.append(f"{change}/index")
    wanted[out_dir / GEN_INDEX] = render_root_index(change_indexes)

    # stale generated files: ours (carry MARKER) but no longer wanted
    stale = [p for p in out_dir.rglob("*.md")
             if p not in wanted and "_build" not in p.parts and is_generated(p)]
    changed = [p for p, text in wanted.items()
               if not p.exists() or p.read_text(encoding="utf-8") != text]

    for n in notes:
        print(f"note: {n}")
    for c in clashes:
        print(f"error: duplicate ID {c}")
    if clashes:
        print("error: set `x-mbselite_id_prefix: XX` in one change's .openspec.yaml to keep its IDs apart")
    if a.check:
        for p in changed + stale:
            print(f"out of date: {p.relative_to(root)}")
        return 1 if (changed or stale or clashes) else 0
    for p in changed:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(wanted[p], encoding="utf-8")
    for p in stale:
        p.unlink()
    print(f"openspec2mbselite: {len(change_indexes)} change(s), {n_req} requirement(s); "
          f"{len(changed)} file(s) written, {len(stale)} stale removed")
    return 1 if clashes else 0


if __name__ == "__main__":
    sys.exit(main())
